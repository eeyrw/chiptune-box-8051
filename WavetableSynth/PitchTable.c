uint32_t WavetablePitchToIncrement(uint16_t pitch)
{
    uint8_t note;
    uint8_t fraction;
    uint32_t base, delta;
    if (!pitch) return 0;
    note = (uint8_t)(pitch >> 8);
    fraction = (uint8_t)pitch;
    if (note >= 128) return pitchIncrement[128];
    base = pitchIncrement[note];
    delta = pitchIncrement[note + 1] - base;
    return base + (delta * fraction >> 8);
}
